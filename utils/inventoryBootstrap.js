async function ensureInventorySeeded() {
  if (process.env.ENABLE_INVENTORY_SEEDING !== 'true') {
    // Explicit opt-in flag required; disabled by default to safeguard production data.
    return;
  }
  try {
    const matCount = await Material.countDocuments();
    if (matCount === 0) {
      console.log('🔄 [Inventory Bootstrap] Material collection is empty. Seeding standard inventory items...');
      await Material.insertMany(DEFAULT_MATERIALS);
      console.log(`✅ [Inventory Bootstrap] Successfully seeded ${DEFAULT_MATERIALS.length} genuine materials.`);
    }

    const pricingCount = await PricingConfig.countDocuments();
    if (pricingCount === 0) {
      console.log('🔄 [Inventory Bootstrap] PricingConfig collection is empty. Seeding standard pricing rules...');
      await PricingConfig.insertMany(DEFAULT_PRICING_CONFIGS);
      console.log(`✅ [Inventory Bootstrap] Successfully seeded ${DEFAULT_PRICING_CONFIGS.length} pricing rules.`);
    }
  } catch (err) {
    console.error('⚠️ [Inventory Bootstrap] Error ensuring inventory seeded:', err.message);
  }
}

